"""Deterministic, clearly-labelled synthetic test images.

Every image produced here is generated by code and stamped with a visible
``SYNTHETIC TEST IMAGE`` banner. None of it is research data, and none of it
may be used to support any scientific claim. The generators exist only so the
test suite can exercise intake, quality assessment and preprocessing with
known-good and known-bad inputs.

All functions are deterministic (fixed seeds) so measurements such as the
Laplacian variance are stable across runs and platforms.
"""

from __future__ import annotations

import cv2
import numpy as np

LABEL = "SYNTHETIC TEST IMAGE - NOT RESEARCH DATA"
DEFAULT_WIDTH = 512
DEFAULT_HEIGHT = 384


def _label(image: np.ndarray, text: str = LABEL) -> np.ndarray:
    """Stamp a visible warning banner onto an image (in place, then return)."""
    height, width = image.shape[:2]
    scale = max(0.35, min(0.7, width / 900.0))
    thickness = max(1, int(round(scale * 2)))
    origin = (8, max(14, int(height * 0.06)))
    color = 255 if float(image.mean()) < 128 else 0
    cv2.putText(
        image,
        text,
        origin,
        cv2.FONT_HERSHEY_SIMPLEX,
        scale,
        color,
        thickness,
        cv2.LINE_AA,
    )
    return image


def mid_gray(
    width: int = DEFAULT_WIDTH, height: int = DEFAULT_HEIGHT, value: int = 128
) -> np.ndarray:
    """Flat mid-gray BGR image with the synthetic banner."""
    image = np.full((height, width, 3), value, dtype=np.uint8)
    return _label(image)


def sharp_texture(
    width: int = DEFAULT_WIDTH, height: int = DEFAULT_HEIGHT, block: int = 8
) -> np.ndarray:
    """High-frequency checkerboard: a sharp image with a high blur variance."""
    rows = height // block + 1
    cols = width // block + 1
    pattern = ((np.add.outer(np.arange(rows), np.arange(cols)) % 2) * 200 + 28).astype(
        np.uint8
    )
    tiled = np.kron(pattern, np.ones((block, block), dtype=np.uint8))[:height, :width]
    image = cv2.cvtColor(tiled, cv2.COLOR_GRAY2BGR)
    return _label(image)


def blurry(
    width: int = DEFAULT_WIDTH, height: int = DEFAULT_HEIGHT, sigma: float = 6.0
) -> np.ndarray:
    """A defocused image: the labelled texture smoothed as a whole.

    The banner is applied *before* blurring so the entire frame is genuinely
    defocused; re-stamping it afterwards would reintroduce sharp edges and
    invalidate the blur measurement.
    """
    return cv2.GaussianBlur(sharp_texture(width, height), (0, 0), sigma)


def low_contrast(
    width: int = DEFAULT_WIDTH, height: int = DEFAULT_HEIGHT
) -> np.ndarray:
    """Narrow intensity spread around mid-gray (low standard deviation)."""
    rng = np.random.default_rng(20260101)
    noise = rng.integers(-4, 5, size=(height, width), dtype=np.int16)
    gray = np.clip(128 + noise, 0, 255).astype(np.uint8)
    return _label(cv2.cvtColor(gray, cv2.COLOR_GRAY2BGR))


def dark(width: int = DEFAULT_WIDTH, height: int = DEFAULT_HEIGHT) -> np.ndarray:
    """Underexposed image (mean brightness well below the default floor)."""
    rng = np.random.default_rng(20260102)
    noise = rng.integers(-3, 4, size=(height, width), dtype=np.int16)
    gray = np.clip(18 + noise, 0, 255).astype(np.uint8)
    return _label(cv2.cvtColor(gray, cv2.COLOR_GRAY2BGR))


def bright(width: int = DEFAULT_WIDTH, height: int = DEFAULT_HEIGHT) -> np.ndarray:
    """Overexposed image (mean brightness well above the default ceiling)."""
    rng = np.random.default_rng(20260103)
    noise = rng.integers(-3, 4, size=(height, width), dtype=np.int16)
    gray = np.clip(242 + noise, 0, 255).astype(np.uint8)
    return _label(cv2.cvtColor(gray, cv2.COLOR_GRAY2BGR))


def clipped(width: int = DEFAULT_WIDTH, height: int = DEFAULT_HEIGHT) -> np.ndarray:
    """Half pure black, half pure white: a large clipped-pixel fraction."""
    image = np.zeros((height, width, 3), dtype=np.uint8)
    image[:, width // 2 :] = 255
    return _label(image)


def clean_texture(
    width: int = 512, height: int = 512
) -> np.ndarray:
    """A well-exposed, high-contrast, unclipped image with no warnings.

    Random uniform noise in ``[60, 200]`` gives a high Laplacian variance,
    a mean near 130, a standard deviation near 40 and zero clipped pixels.
    """
    rng = np.random.default_rng(20260104)
    gray = rng.integers(60, 201, size=(height, width), dtype=np.uint8)
    return cv2.cvtColor(gray, cv2.COLOR_GRAY2BGR)


def gradient(
    width: int = DEFAULT_WIDTH, height: int = DEFAULT_HEIGHT
) -> np.ndarray:
    """A left-to-right brightness ramp, useful for illumination correction."""
    ramp = np.linspace(20, 235, width, dtype=np.uint8)
    gray = np.tile(ramp, (height, 1))
    return cv2.cvtColor(gray, cv2.COLOR_GRAY2BGR)


def encode(image: np.ndarray, fmt: str = "png", *, quality: int = 92) -> bytes:
    """Encode a BGR array to bytes using the requested container."""
    fmt = fmt.lower()
    if fmt in {"jpg", "jpeg"}:
        extension, params = ".jpg", [cv2.IMWRITE_JPEG_QUALITY, int(quality)]
    elif fmt == "webp":
        extension, params = ".webp", [cv2.IMWRITE_WEBP_QUALITY, int(quality)]
    elif fmt == "png":
        extension, params = ".png", [cv2.IMWRITE_PNG_COMPRESSION, 3]
    else:
        raise ValueError(f"unsupported fixture format: {fmt!r}")
    ok, buffer = cv2.imencode(extension, image, params)
    if not ok:  # pragma: no cover - encoding valid arrays is reliable
        raise RuntimeError(f"failed to encode fixture as {fmt}")
    return buffer.tobytes()


def valid_png(**kwargs) -> bytes:
    return encode(sharp_texture(**kwargs), "png")


def valid_jpeg(**kwargs) -> bytes:
    return encode(sharp_texture(**kwargs), "jpeg")


def valid_webp(**kwargs) -> bytes:
    return encode(sharp_texture(**kwargs), "webp")


def tiny_png(size: int = 64) -> bytes:
    """A valid PNG below the default 128 px minimum dimension."""
    return encode(mid_gray(size, size), "png")


def corrupt_png() -> bytes:
    """A PNG header followed by garbage: detectable format, undecodable body."""
    return b"\x89PNG\r\n\x1a\n" + b"\x00" * 32


def truncated_png() -> bytes:
    """The first bytes of a real PNG: valid magic, truncated pixel data."""
    return valid_png()[:64]


def empty_bytes() -> bytes:
    return b""


def unsupported_bytes() -> bytes:
    """Plain text with a supported-looking extension is still unsupported."""
    return b"this is definitely not an image\n" * 4


def animated_gif_bytes() -> bytes:
    """A real but unsupported format (GIF89a magic)."""
    return b"GIF89a" + b"\x00" * 64


def with_exif_orientation(
    orientation: int = 6,
    width: int = 320,
    height: int = 240,
) -> bytes:
    """A JPEG carrying an EXIF orientation tag (pixel data is unrotated)."""
    from io import BytesIO

    from PIL import Image

    image = Image.fromarray(cv2.cvtColor(mid_gray(width, height), cv2.COLOR_BGR2RGB))
    exif = Image.Exif()
    exif[274] = orientation
    exif[36867] = "2026:01:02 03:04:05"
    exif[271] = "SyntheticMake"
    buffer = BytesIO()
    image.save(buffer, format="JPEG", exif=exif, quality=92)
    return buffer.getvalue()
